    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
         int filaSeleccionada = tablaReservas.getSelectedRow();
        if (filaSeleccionada < 0) {
            UtilGui.showErrorMessage(this, "Seleccione una reserva", "Error");
            return;
        }
        
        DefaultTableModel modelo = (DefaultTableModel) tablaReservas.getModel();
        String estado = (String) modelo.getValueAt(filaSeleccionada, 4);
        
        if (!estado.equals("Activa")) {
            UtilGui.showErrorMessage(this, "Solo se pueden modificar reservas activas", "Error");
            return;
        }
        
        String[] opciones = {"Sedán", "SUV", "Pick-up"};
        String tipoStr = (String) JOptionPane.showInputDialog(this,
            "Seleccione nuevo tipo de vehículo:",
            "Modificar Reserva",
            JOptionPane.QUESTION_MESSAGE,
            null,
            opciones,
            "Sedán");
        
        if (tipoStr != null) {
            TipoVehiculo nuevoTipo = obtenerTipoPorDescripcion(tipoStr);
            Reservas reservaSeleccionada = buscarReservaPorFila(filaSeleccionada);
            if (reservaSeleccionada != null) {
                if (listaReservas.modificarVehiculo(reservaSeleccionada, nuevoTipo)) {
                    UtilGui.showMessage(this, "Reserva modificada exitosamente", "Éxito");
                    cargarTablaReservas();
                } else {
                    UtilGui.showErrorMessage(this, "No hay vehículos disponibles del tipo seleccionado", "Error");
                }
            }
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnCancelarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarActionPerformed
          int filaSeleccionada = tablaReservas.getSelectedRow();
        if (filaSeleccionada < 0) {
            UtilGui.showErrorMessage(this, "Seleccione una reserva para cancelar", "Error");
            return;
        }
        
        int confirmacion = JOptionPane.showConfirmDialog(this, 
            "¿Está seguro de cancelar esta reserva?", 
            "Confirmar cancelación", 
            JOptionPane.YES_NO_OPTION);
            
        if (confirmacion == JOptionPane.YES_OPTION) {
            Reservas reservaAEliminar = buscarReservaPorFila(filaSeleccionada);
            
            if (reservaAEliminar != null && listaReservas.eliminar(reservaAEliminar)) {
                UtilGui.showMessage(this, "Reserva cancelada exitosamente", "Información");
                cargarTablaReservas();
            } else {
                UtilGui.showErrorMessage(this, "No se pudo cancelar la reserva", "Error");
            }
        }
    }//GEN-LAST:event_btnCancelarActionPerformed


private boolean validarCampos() {
        if (cmbClientes.getSelectedIndex() == 0) {
            UtilGui.showErrorMessage(this, "Seleccione un cliente", "Error");
            return false;
        }
        
        if (cmbTipoVehiculo.getSelectedIndex() == 0) {
            UtilGui.showErrorMessage(this, "Seleccione un tipo de vehículo", "Error");
            return false;
        }
        
        if (!UtilGui.validateRequiere(txtFechaInicio, txtFechaFin)) {
            UtilGui.showErrorMessage(this, "Complete todas las fechas", "Error");
            return false;
        }
        
        try {
            LocalDate fechaInicio = LocalDate.parse(txtFechaInicio.getText(), DateTimeFormatter.ofPattern("dd/MM/yyyy"));
            LocalDate fechaFin = LocalDate.parse(txtFechaFin.getText(), DateTimeFormatter.ofPattern("dd/MM/yyyy"));
            
            if (fechaInicio.isBefore(LocalDate.now())) {
                UtilGui.showErrorMessage(this, "La fecha de inicio no puede ser anterior a hoy", "Error");
                return false;
            }
            
            if (!fechaFin.isAfter(fechaInicio)) {
                UtilGui.showErrorMessage(this, "La fecha de fin debe ser posterior a la de inicio", "Error");
                return false;
            }
            
            if (fechaInicio.until(fechaFin).getDays() > 30) {
                UtilGui.showErrorMessage(this, "No se permiten reservas de más de 30 días", "Error");
                return false;
            }
            
        } catch (DateTimeParseException e) {
            UtilGui.showErrorMessage(this, "Formato de fecha incorrecto. Use dd/MM/yyyy", "Error");
            return false;
        }
        
        return true;
    }

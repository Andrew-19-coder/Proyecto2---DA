 private Reservas buscarReservaPorFila(int fila) {
        DefaultTableModel modelo = (DefaultTableModel) tablaReservas.getModel();
        String nombreCliente = (String) modelo.getValueAt(fila, 0);
        String estado = (String) modelo.getValueAt(fila, 4);
        String fechaInicio = (String) modelo.getValueAt(fila, 2);
        
        LocalDate fecha = LocalDate.parse(fechaInicio, DateTimeFormatter.ofPattern("dd/MM/yyyy"));
        
        if (estado.equals("Activa")) {
            for (Reservas r : listaReservas.getReservasActivas()) {
                if (r.getCliente().getNombre().equals(nombreCliente) &&
                    r.getFechaInicioAlquiler().equals(fecha)) {
                    return r;
                }
            }
        } else {
            for (Reservas r : listaReservas.getReservasEspera()) {
                if (r.getCliente().getNombre().equals(nombreCliente) &&
                    r.getFechaInicioAlquiler().equals(fecha)) {
                    return r;
                }
            }
        }
        return null;
 }
    private void mostrarResultadosBusqueda(ArrayList<Reservas> resultados) {
        DefaultTableModel modelo = (DefaultTableModel) tablaReservas.getModel();
        modelo.setRowCount(0);
        
        if (resultados.isEmpty()) {
            UtilGui.showMessage(this, "No se encontraron reservas", "Información");
            cargarTablaReservas();
            return;
        }
        
        for (Reservas r : resultados) {
            String vehiculoInfo = r.getVehiculo() != null ? 
                r.getVehiculo().getPlaca() + " - " + r.getVehiculo().getMarca() : 
                "Sin asignar";
                
            Object[] fila = {
                r.getCliente().getNombre(),
                vehiculoInfo,
                r.getFechaInicioAlquiler().format(DateTimeFormatter.ofPattern("dd/MM/yyyy")),
                r.getFechaFinAlquiler().format(DateTimeFormatter.ofPattern("dd/MM/yyyy")),
                r.getVehiculo() != null ? "Activa" : "En Espera"
            };
            modelo.addRow(fila);
        }
        
        UtilGui.showMessage(this, "Se encontraron " + resultados.size() + " reservas", "Resultados");
    }
    private TipoVehiculo obtenerTipoPorDescripcion(String descripcion) {
        for (TipoVehiculo tipo : TipoVehiculo.values()) {
            if (tipo.getDescripcion().equals(descripcion)) {
                return tipo;
            }
        }
        return null;
    }
    
    
    
